import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser=await chromium.launch({executablePath:process.env.ORBITAL_BROWSER||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:960}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
  await page.goto(new URL('../dist/index.html',import.meta.url).href);
  await page.evaluate(()=>{orbital.load('playground');orbital.closeModal();});
  await page.locator('#collision-controls summary').click();
  const ids=await page.evaluate(()=>{
    const w=orbital.world,a=w.units.find(u=>u.type==='rock'),b=w.units.filter(u=>u.type==='rock')[1],booster=w.units.find(u=>u.id===a.boosterId);
    w.planets=[];w.units=[a,b,booster];
    Object.assign(a,{x:200,y:100,vx:0,vy:0,beltOrbit:null});
    Object.assign(b,{x:260,y:100,vx:0,vy:0,beltOrbit:null,team:'neutral',boosterTeam:null,boosterId:null});
    orbital.tuneGravity({g:0});orbital.select(a.id);orbital.plan({id:a.id,impulse:{x:20,y:0}});
    window.collisionNodes=[...document.querySelectorAll('[data-collision]')];
    return {a:a.id,b:b.id};
  });
  await page.locator('#collision-strength').fill('100');
  await page.locator('#collision-bounce').fill('1');
  assert.equal(await page.evaluate(()=>orbital.paused),true);
  const before=await page.evaluate(()=>structuredClone(orbital.world.units));
  let forecast=await page.evaluate(ids=>({a:orbital.ui.predictions.get(ids.a),b:orbital.ui.predictions.get(ids.b)}),ids);
  assert.equal(forecast.a.collisions[0].kind,'deflect');assert.equal(forecast.b.secondary,true);
  assert.ok((await page.locator('#selected-meta').innerText()).includes('mass 2 / impact 65'));
  await page.locator('#collision-strength').fill('1');
  assert.deepEqual(await page.evaluate(()=>orbital.world.units),before);
  assert.equal(await page.evaluate(ids=>orbital.ui.predictions.get(ids.a).collisions[0].kind,ids),'smash');
  await page.locator('#collision-strength').fill('100');
  await page.locator('#collision-bounce').focus();await page.keyboard.press('ArrowLeft');
  assert.equal(await page.evaluate(()=>orbital.world.collisions.bounce),.95);
  assert.ok(await page.evaluate(()=>collisionNodes.every(n=>n.isConnected)));
  await page.locator('#collision-bounce').fill('0.35');
  await mkdir('test-results',{recursive:true});await page.screenshot({path:'test-results/orbital-collisions.png'});
  await page.locator('#confirm').click();await page.locator('#autopause').uncheck();await page.locator('[data-speed="5"]').click();
  await page.waitForFunction(()=>orbital.world.events.some(e=>e.text==='Rock deflection'));
  await page.locator('#pause').click();
  assert.ok(await page.evaluate(id=>orbital.world.units.find(u=>u.id===id).vx>0,ids.b));
  const settings=await page.evaluate(()=>({...orbital.world.collisions}));
  await page.locator('#range-reset').click();
  assert.deepEqual(await page.evaluate(()=>orbital.world.collisions),settings);
  await page.locator('#collision-reset').click();
  assert.deepEqual(await page.evaluate(()=>orbital.world.collisions),{bounce:.35,strength:18});
  await page.setViewportSize({width:390,height:844});
  await page.locator('#collision-strength').scrollIntoViewIfNeeded();await page.locator('#collision-strength').fill('40');
  assert.equal(await page.evaluate(()=>orbital.world.collisions.strength),40);
  await page.screenshot({path:'test-results/orbital-collisions-mobile.png'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
  assert.deepEqual(errors,[]);
  console.log('Collision UI passed: stable sliders, both forecast paths, size/mass/damage, smash preview, real deflection, settings reset/restart, mobile controls.');
}finally{await browser.close();}
